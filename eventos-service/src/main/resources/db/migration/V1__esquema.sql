CREATE TABLE evento (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             BIGINT        NOT NULL,
    cliente_id          VARCHAR(100)  NOT NULL,
    creado_por          VARCHAR(100)  NOT NULL,
    inicio              TIMESTAMP     NOT NULL,
    fin                 TIMESTAMP     NOT NULL,
    asistentes          INTEGER       NOT NULL CHECK (asistentes > 0),
    estado              VARCHAR(12)   NOT NULL,
    precio_total        NUMERIC(14,2) NOT NULL,
    senia_monto         NUMERIC(14,2) NOT NULL,
    senia_abonada       BOOLEAN       NOT NULL,
    senia_reembolsable  BOOLEAN,
    codigo_rechazo      VARCHAR(60),
    motivo_rechazo      VARCHAR(500),
    creado_en           TIMESTAMP     NOT NULL,
    CONSTRAINT ck_evento_periodo CHECK (fin > inicio)
);

CREATE INDEX ix_evento_cliente ON evento (cliente_id, inicio);

-- instalacion_id y servicio_id referencian a recursos-service: sin clave foránea, cada servicio es dueño de sus datos.
CREATE TABLE evento_instalacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id         BIGINT        NOT NULL REFERENCES evento (id),
    instalacion_id    BIGINT        NOT NULL,
    nombre            VARCHAR(100)  NOT NULL,
    aire_libre        BOOLEAN       NOT NULL,
    tarifa_hora       NUMERIC(12,2) NOT NULL,
    horas_facturadas  BIGINT        NOT NULL,
    subtotal          NUMERIC(14,2) NOT NULL
);

CREATE TABLE evento_servicio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id        BIGINT        NOT NULL REFERENCES evento (id),
    servicio_id      BIGINT        NOT NULL,
    nombre           VARCHAR(100)  NOT NULL,
    cantidad         INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12,2) NOT NULL,
    subtotal         NUMERIC(14,2) NOT NULL
);

CREATE TABLE historial_estado_evento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id        BIGINT       NOT NULL REFERENCES evento (id),
    estado_anterior  VARCHAR(12),
    estado_nuevo     VARCHAR(12)  NOT NULL,
    motivo           VARCHAR(500),
    usuario          VARCHAR(100) NOT NULL,
    fecha            TIMESTAMP    NOT NULL
);

CREATE TABLE advertencia_meteorologica (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id            BIGINT           NOT NULL REFERENCES evento (id),
    consultada_en        TIMESTAMP        NOT NULL,
    probabilidad_lluvia  INTEGER          NOT NULL,
    rafaga_viento_kmh    DOUBLE PRECISION NOT NULL,
    granizo              BOOLEAN          NOT NULL,
    detalle              VARCHAR(500)     NOT NULL
);
