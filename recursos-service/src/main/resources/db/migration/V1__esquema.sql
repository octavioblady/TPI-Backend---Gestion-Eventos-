CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE instalacion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100)  NOT NULL UNIQUE,
    descripcion  VARCHAR(500),
    capacidad    INTEGER       NOT NULL CHECK (capacidad > 0),
    aire_libre   BOOLEAN       NOT NULL,
    activa       BOOLEAN       NOT NULL,
    tarifa_hora  NUMERIC(12,2) NOT NULL CHECK (tarifa_hora > 0)
);

CREATE TABLE horario_instalacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instalacion_id  BIGINT      NOT NULL REFERENCES instalacion (id),
    dia             VARCHAR(10) NOT NULL,
    apertura        TIME        NOT NULL,
    cierre          TIME        NOT NULL,
    CONSTRAINT uk_horario_instalacion_dia UNIQUE (instalacion_id, dia),
    CONSTRAINT ck_horario_valido CHECK (cierre > apertura)
);

CREATE TABLE equipamiento_instalacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instalacion_id  BIGINT       NOT NULL REFERENCES instalacion (id),
    nombre          VARCHAR(100) NOT NULL,
    cantidad        INTEGER      NOT NULL CHECK (cantidad > 0)
);

CREATE TABLE mantenimiento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instalacion_id  BIGINT       NOT NULL REFERENCES instalacion (id),
    desde           TIMESTAMP    NOT NULL,
    hasta           TIMESTAMP    NOT NULL,
    motivo          VARCHAR(300),
    estado          VARCHAR(12)  NOT NULL,
    CONSTRAINT ck_mantenimiento_periodo CHECK (hasta > desde)
);

CREATE TABLE servicio_complementario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100)  NOT NULL UNIQUE,
    descripcion      VARCHAR(500),
    precio_unitario  NUMERIC(12,2) NOT NULL CHECK (precio_unitario > 0),
    stock_total      INTEGER       NOT NULL CHECK (stock_total >= 0),
    activo           BOOLEAN       NOT NULL
);

CREATE TABLE stock_servicio_fecha (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio_id         BIGINT  NOT NULL REFERENCES servicio_complementario (id),
    fecha               DATE    NOT NULL,
    cantidad_reservada  INTEGER NOT NULL CHECK (cantidad_reservada >= 0),
    CONSTRAINT uk_stock_servicio_fecha UNIQUE (servicio_id, fecha)
);

-- evento_id referencia a eventos-service: no hay clave foránea porque cada servicio tiene su propia base.
CREATE TABLE reserva_espacio (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       BIGINT      NOT NULL,
    instalacion_id  BIGINT      NOT NULL REFERENCES instalacion (id),
    inicio          TIMESTAMP   NOT NULL,
    fin             TIMESTAMP   NOT NULL,
    estado          VARCHAR(10) NOT NULL,
    CONSTRAINT ck_reserva_periodo CHECK (fin > inicio),
    -- Garantía final contra la doble reserva, aun con solicitudes simultáneas.
    CONSTRAINT ex_reserva_espacio_sin_solape EXCLUDE USING gist (
        instalacion_id WITH =,
        tsrange(inicio, fin) WITH &&
    ) WHERE (estado = 'ACTIVA')
);

CREATE INDEX ix_reserva_espacio_evento ON reserva_espacio (evento_id, estado);

CREATE TABLE reserva_servicio (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id    BIGINT      NOT NULL,
    servicio_id  BIGINT      NOT NULL REFERENCES servicio_complementario (id),
    fecha        DATE        NOT NULL,
    cantidad     INTEGER     NOT NULL CHECK (cantidad > 0),
    estado       VARCHAR(10) NOT NULL
);

CREATE INDEX ix_reserva_servicio_evento ON reserva_servicio (evento_id, estado);
